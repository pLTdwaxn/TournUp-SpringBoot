package com.abeesmall.tournup.tenancy

import com.abeesmall.tournup.TestcontainersConfiguration
import com.abeesmall.tournup.catalog.TenantCatalog
import com.abeesmall.tournup.catalog.TenantDatabaseBinding
import java.net.URI
import java.util.UUID
import javax.sql.DataSource
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue
import org.flywaydb.core.Flyway
import org.junit.jupiter.api.Test
import org.mockito.Mockito.mock
import org.mockito.Mockito.`when` as whenever
import org.springframework.beans.factory.annotation.Autowired
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest
import org.springframework.boot.flyway.autoconfigure.FlywayProperties
import org.springframework.boot.jdbc.test.autoconfigure.AutoConfigureTestDatabase
import org.springframework.context.annotation.Import

@DataJpaTest
@AutoConfigureTestDatabase(replace = AutoConfigureTestDatabase.Replace.NONE)
@Import(TestcontainersConfiguration::class)
class TenantMigrationStrategyTests(@Autowired private val dataSource: DataSource) {
    @Test
    fun `runtime grants cover existing and future data tables without granting migration history access`() {
        val suffix = UUID.randomUUID().toString().replace("-", "")
        val schema = "grants_$suffix"
        val role = "runtime_$suffix"
        val catalog = mock(TenantCatalog::class.java)
        dataSource.connection.use { connection ->
            val metadata = connection.metaData
            val url = metadata.url
            val uri = URI(url.removePrefix("jdbc:"))
            val properties = FlywayProperties().apply {
                this.url = url
                user = metadata.userName
            }
            whenever(catalog.findActiveDatabaseBindings("tournup-api")).thenReturn(listOf(
                TenantDatabaseBinding(UUID.randomUUID(), "tournup-api", uri.host, uri.port,
                    uri.path.removePrefix("/"), role, "unused", 1),
            ))
            // Match the URL reconstruction performed by the strategy (without driver query parameters).
            properties.url = "jdbc:postgresql://${uri.host}:${uri.port}${uri.path}"
            val flyway = Flyway.configure().dataSource(dataSource).schemas(schema).defaultSchema(schema).load()
            val strategy = TenantMigrationStrategy(catalog, properties)
            connection.createStatement().use { sql ->
                sql.execute("CREATE ROLE $role")
                try {
                    strategy.migrate(flyway)
                    strategy.migrate(flyway) // Repeated dev startup must remain safe.
                    sql.executeQuery("SELECT has_table_privilege('$role', '$schema.flyway_schema_history', 'INSERT')").use {
                        assertTrue(it.next()); assertFalse(it.getBoolean(1))
                    }
                    sql.execute("SET ROLE $role")
                    try {
                        sql.executeQuery("SELECT count(*) FROM $schema.tournaments").use {
                            assertTrue(it.next()); assertEquals(0, it.getInt(1))
                        }
                        sql.execute("INSERT INTO $schema.audit_revisions(timestamp_ms) VALUES (1)")
                    } finally {
                        sql.execute("RESET ROLE")
                    }
                    sql.execute("CREATE TABLE $schema.future_resource (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)")
                    sql.execute("SET ROLE $role")
                    try {
                        sql.execute("INSERT INTO $schema.future_resource DEFAULT VALUES")
                        sql.executeQuery("SELECT count(*) FROM $schema.future_resource").use {
                            assertTrue(it.next()); assertEquals(1, it.getInt(1))
                        }
                    } finally {
                        sql.execute("RESET ROLE")
                    }
                } finally {
                    sql.execute("DROP SCHEMA IF EXISTS $schema CASCADE")
                    sql.execute("DROP ROLE $role")
                }
            }
        }
    }
}
